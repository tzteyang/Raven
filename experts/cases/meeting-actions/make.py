def compare(m, rule):
    """这道题每件事按本规则、按另外两套规则、按几种常见错误口径的结果，用来校验陷阱有效。"""
    r = RULES[rule]
    out = []
    for rec in m["recs"]:
        mine = judge(rec, r, m["meeting"])
        variants = {other: judge(rec, RULES[other], m["meeting"]) for other in RULES if other != rule}
        variants["不看日历"] = judge(rec, r, m["meeting"], blind_kind)
        variants["调休算反"] = judge(rec, {**r, "makeup": not r["makeup"]}, m["meeting"])
        variants["顺延提前反"] = judge(rec, {**r, "shift": "earlier" if r["shift"] == "later" else "later"}, m["meeting"])
        out.append((rec, mine, variants))
    return out


def same_result(a, b) -> bool:
    return a["place"] == b["place"] and a.get("date") == b.get("date")


def validate(spec, m, rule, rows, extra, dropped, text):
    name, group, segment = spec[:3]
    meeting = m["meeting"]
    lines = m["lines"]
    kws = [rec["kw"] for rec in m["recs"]]
    assert len(set(kws)) == len(kws), (name, kws)
    for rec in m["recs"]:
        own = {id(x) for x in rec["first"] + rec["later"]}
        for line in lines:
            if rec["kw"] in line[1]:
                assert id(line) in own, (name, rec["kw"], line[1])
        assert any(rec["kw"] in x for _, x in rec["first"]), (name, rec["kw"])
    for rec, o, _ in rows + extra:
        if o.get("date") is not None:
            assert o["date"] > meeting, (name, rec["kw"], o["date"])
    assert extra, (name, "every question needs something to confirm")
    size = len(re.sub(r"\s", "", text))
    assert size <= RULES[rule]["limit"] - 40, (name, size, RULES[rule]["limit"])
    table = compare(m, rule)
    dated = [(rec, mine, v) for rec, mine, v in table if mine["place"] != "drop" and mine["date"] is not None]
    by_calendar = [rec["kw"] for rec, mine, v in dated
                   if not same_result(mine, v["不看日历"]) or not same_result(mine, v["调休算反"])]
    if segment == "common":
        assert not by_calendar, (name, "common questions must not depend on holidays", by_calendar)
    else:
        assert len(by_calendar) >= 2, (name, "edge questions need dates that depend on the calendar", by_calendar)
        tricky = [rec["kw"] for rec, mine, v in dated if any(not same_result(mine, x) for x in v.values())]
        assert len(tricky) >= 3, (name, tricky)
    others = ["R1", "R2"] if rule == "R3" else [{"R1": "R2", "R2": "R1"}[rule]]
    for other in others:
        differ = [rec["kw"] for rec, mine, v in table if not same_result(mine, v[other])]
        assert len(differ) >= 2, (name, other, differ)
    for _, x in lines:
        if any(t in x for t in ("周六", "周日")):
            raise AssertionError((name, "weekend phrase", x))
    return {"chars": size, "calendar": len(by_calendar)}


def check_vocabulary() -> None:
    for rule in RULES:
        names = {p.name for p in PEOPLE[rule]} | {p.nick for p in PEOPLE[rule]} | {p.title for p in PEOPLE[rule]}
        nicks = Counter(p.nick for p in PEOPLE[rule])
        assert max(nicks.values()) == 1, rule
        kws = [t.kw for t in ITEMS[rule]]
        for t in ITEMS[rule]:
            assert t.kw in t.said, t
            for other in ITEMS[rule]:
                if other is not t:
                    assert t.kw not in other.said, (t.kw, other.said)
        for f in [line for talk in TALK[rule] for line in talk] + SHORT:
            bad = [w for w in TRIGGERS + kws + sorted(names) if w in f] + re.findall(r"周[一二三四五六日]", f)
            assert not bad, (rule, f, bad)
        for word in MISSING[rule]:
            assert word not in {p.title for p in PEOPLE[rule]}, word


