# ---------------------------------------------------------------- 日历和日期

def kind_of(d: date) -> str:
    if d in HOLIDAYS:
        return "节假日"
    if d in MAKEUP:
        return "调休上班"
    return "休息日" if d.weekday() >= 5 else "工作日"


def blind_kind(d: date) -> str:
    """不看日历的人：只认周一到周五是工作日。"""
    return "休息日" if d.weekday() >= 5 else "工作日"


def working(d, r, cal) -> bool:
    k = cal(d)
    return k == "工作日" or (k == "调休上班" and r["makeup"])


def show(d: date) -> str:
    return f"{d.isoformat()}（周{WEEK[d.weekday()]}）"


def short(d: date) -> str:
    return f"{d.month:02d}-{d.day:02d}"


def styled(d, r) -> str:
    if d is None:
        return "待定"
    if r["style"] == "iso":
        return d.isoformat()
    if r["style"] == "cn":
        return f"{d.month}月{d.day}日（周{WEEK[d.weekday()]}）"
    return d.strftime("%Y/%m/%d")


def count_workdays(start, n, r, cal) -> list:
    seen, d = [], start
    while len(seen) < n:
        if working(d, r, cal):
            seen.append(d)
        d += timedelta(days=1)
    return seen


def what_day(d, r, cal) -> str:
    k = cal(d)
    note = HOLIDAYS.get(d) if k == "节假日" else ""
    rule = ""
    if k == "调休上班":
        rule = "，本规则算工作日" if r["makeup"] else "，本规则不算工作日"
    return f"{k}{'（' + note + '）' if note else ''}{rule}"


def settle(raw, r, cal, how):
    if working(raw, r, cal):
        return raw, f"{how} {show(raw)}，日历上是{what_day(raw, r, cal)}，就取这一天"
    step = 1 if r["shift"] == "later" else -1
    d = raw
    while not working(d, r, cal):
        d += timedelta(days=step)
    move = "顺延到之后" if step > 0 else "提前到之前最近"
    return d, f"{how} {show(raw)}，日历上是{what_day(raw, r, cal)}，不是工作日，{move}的工作日 {show(d)}"


def due(phrase, meeting, r, cal=kind_of):
    """按这套规则把会上说的时间换成截止日期：(日期或 None, 怎么推出来的)。"""
    if not phrase:
        return None, "会上没说时间，写“待定”"
    if phrase in VAGUE:
        if r["vague"] == "pending":
            return None, f"只说了“{phrase}”，写“待定”"
        seen = count_workdays(meeting + timedelta(days=1), 2, r, cal)
        return seen[-1], (f"“{phrase}”：从会议次日起数工作日，{'、'.join(short(d) for d in seen)}，"
                          f"第 2 个是 {show(seen[-1])}")
    found = re.fullmatch(r"(下)?周([一二三四五六日])前?", phrase)
    if found:
        target = WEEK.index(found.group(2))
        if found.group(1):
            monday = meeting - timedelta(days=meeting.weekday()) + timedelta(days=7)
            raw = monday + timedelta(days=target)
            how = f"“{phrase}”：会议所在周的下一周是 {short(monday)} 至 {short(monday + timedelta(days=6))}，其中的周{found.group(2)}是"
        else:
            raw = meeting + timedelta(days=(target - meeting.weekday()) % 7 or 7)
            how = f"“{phrase}”：会议日期之后最近的周{found.group(2)}是"
        return settle(raw, r, cal, how)
    if phrase == "明天":
        return settle(meeting + timedelta(days=1), r, cal, "“明天”：会议日期的下一天是")
    found = re.fullmatch(r"(下个)?月底前?", phrase)
    if found:
        year, month = meeting.year, meeting.month + (1 if found.group(1) else 0)
        if month > 12:
            year, month = year + 1, month - 12
        last = date(year, month, calendar.monthrange(year, month)[1])
        if r["month_end"] == "last":
            return settle(last, r, cal, f"“{phrase}”：{month} 月的最后一天是")
        d = last
        while not working(d, r, cal):
            d -= timedelta(days=1)
        tail = "" if d == last else f"（{show(last)} 是{what_day(last, r, cal)}，不是工作日）"
        return d, f"“{phrase}”：{month} 月的最后一个工作日是 {show(d)}{tail}"
    found = re.fullmatch(r"(\d+) 个工作日内", phrase)
    if found:
        n = int(found.group(1))
        start = meeting + timedelta(days=1) if r["count_from"] == "next" else meeting
        seen = count_workdays(start, n, r, cal)
        skipped = []
        d = start
        while d < seen[-1]:
            if not working(d, r, cal):
                skipped.append(f"{short(d)} {what_day(d, r, cal)}")
            d += timedelta(days=1)
        origin = "会议次日" if r["count_from"] == "next" else "会议当天"
        note = f"（跳过：{'；'.join(skipped)}）" if skipped else ""
        return seen[-1], (f"“{phrase}”：从{origin}起数工作日，{'、'.join(short(d) for d in seen)}，"
                          f"第 {n} 个是 {show(seen[-1])}{note}")
    found = re.fullmatch(r"(中秋|国庆)?节后第一天", phrase)
    if found:
        name = found.group(1) + "节" if found.group(1) else None
        d = meeting + timedelta(days=1)
        while not (cal(d) == "节假日" and (name is None or HOLIDAYS.get(d) == name)):
            d += timedelta(days=1)
            if d > meeting + timedelta(days=120):
                return None, "日历里找不到假期"
        begin = d
        while cal(d + timedelta(days=1)) == "节假日":
            d += timedelta(days=1)
        end = d
        d += timedelta(days=1)
        while not working(d, r, cal):
            d += timedelta(days=1)
        which = "说的是" if name else "会议之后最近的假期是"
        return d, f"“{phrase}”：{which}{HOLIDAYS[begin]}（{short(begin)} 至 {short(end)}），结束后的第一个工作日是 {show(d)}"
    raise ValueError(phrase)


def calendar_text(meeting: date) -> str:
    start = meeting.replace(day=1)
    last_month = min(meeting.month + 2, 12)
    end = date(meeting.year, last_month, calendar.monthrange(meeting.year, last_month)[1])
    lines = [f"# 公司日历（{start.isoformat()} 至 {end.isoformat()}）", "",
             "“类型”只有四种：工作日、休息日、节假日、调休上班（周末上班的日子）。", "",
             "| 日期 | 星期 | 类型 | 备注 |", "|---|---|---|---|"]
    d = start
    while d <= end:
        lines.append(f"| {d.isoformat()} | 周{WEEK[d.weekday()]} | {kind_of(d)} | {HOLIDAYS.get(d) or MAKEUP.get(d) or ''} |")
        d += timedelta(days=1)
    return "\n".join(lines) + "\n"


