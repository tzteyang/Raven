def sp(text: str) -> str:
    return " " + text if text[:1].isdigit() else text


def tidy(text: str) -> str:
    text = re.sub(r"([A-Za-z0-9])([一-鿿])", r"\1 \2", text)
    return re.sub(r"([一-鿿])([A-Za-z0-9])", r"\1 \2", text)


def commit(rng, said, verb, dl) -> str:
    if not dl:
        return rng.choice([f"{said}我来{verb}。", f"{said}交给我吧。"])
    return rng.choice([f"{said}我来{verb}，{dl}。", f"{said}交给我，{dl}。", f"{said}我负责，{dl}。"])


